#!/usr/bin/env node
// Regenerates documents/evalsutra/evidence/: real test run output, sample reports and the self-audit.
// Every file is produced by running the shipped CLI; nothing is hand-written. Run: node scripts/build-evidence.mjs
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readJson } from '../packages/core/evaluate.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EV = join(ROOT, 'documents/evalsutra/evidence');
const S = join(EV, 'samples');
const cli = join(ROOT, 'packages/cli/evalsutra.mjs');
const node = process.execPath;
const sh = (args, opts = {}) => spawnSync(node, args, { cwd: ROOT, encoding: 'utf8', ...opts });
const ev = (...a) => sh([cli, ...a]);

rmSync(EV, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
mkdirSync(S, { recursive: true });

// 1. Full test run. Placeholders first so the docs link-check test inside the run can resolve its targets.
for (const f of ['README.md', 'test-run.txt', 'test-summary.json']) writeFileSync(join(EV, f), 'placeholder, overwritten below\n');
mkdirSync(join(S, 'audit'), { recursive: true });
for (const f of ['audit-report.md', 'audit-report.html', 'audit-report.json']) writeFileSync(join(S, 'audit', f), 'placeholder\n');
const t = sh(['--test', '--test-reporter=spec']);
const clean = t.stdout.replace(/\u001b\[[0-9;]*m/g, '');
const num = k => Number(new RegExp(`ℹ ${k} (\\d+)`).exec(clean)?.[1] ?? NaN);
const summary = { tests: num('tests'), pass: num('pass'), fail: num('fail'), skipped: num('skipped'), cancelled: num('cancelled') };
const pkg = readJson(join(ROOT, 'package.json'));
const head = `EvalSutra ${pkg.version} test run\nNode ${process.version} on ${process.platform} ${process.arch}\nCommand: node --test --test-reporter=spec\nExit code: ${t.status}\nNote: durations vary per run; this file is regenerated by scripts/build-evidence.mjs.\n${'-'.repeat(60)}\n`;
writeFileSync(join(EV, 'test-run.txt'), head + clean);
writeFileSync(join(EV, 'test-summary.json'), JSON.stringify({ version: pkg.version, node: process.version, platform: process.platform, exitCode: t.status, ...summary }, null, 2) + '\n');

// 2. Sample evaluations (synthetic observations).
const good = join(S, 'good'), bad = join(S, 'bad');
const r1 = ev('run', '--suite', 'suites/demo.json', '--observations', 'examples/demo-observations.json', '--out', good);
const r2 = ev('run', '--suite', 'suites/demo.json', '--observations', 'examples/demo-observations-bad.json', '--out', bad);
const cmp = ev('compare', '--baseline', join(good, 'report.json'), '--candidate', join(bad, 'report.json'), '--out', join(S, 'compare-good-vs-bad.json'));
const gate = ev('gate', '--report', join(bad, 'report.json'), '--policy', 'policies/default.json');
const trace = ev('trace', 'analyze', '--input', 'examples/traces/bad-trace.json', '--forbid', 'run_tests');
const audit = ev('audit', '--out', join(S, 'audit'));
copyFileSync(join(ROOT, 'suites/demo.json'), join(S, 'demo-suite.json'));
writeFileSync(join(S, 'trace-analysis.json'), trace.stdout);
writeFileSync(join(S, 'gate-bad-run.json'), gate.stdout);

const row = (name, r, expect) => `| \`${name}\` | ${r.status} | ${expect} | ${r.status === expect ? 'yes' : '**NO**'} |`;
const exitTable = [
  row('run (good evidence)', r1, 0), row('run (bad evidence)', r2, 2), row('compare good vs bad', cmp, 2),
  row('gate bad report', gate, 2), row('trace analyze bad trace', trace, 2), row('audit', audit, 0)
].join('\n');

const readme = `# Evidence

Generated by \`node scripts/build-evidence.mjs\` on Node ${process.version} (${process.platform} ${process.arch}). Nothing here is hand-written.

## Test run

| Tests | Passed | Failed | Skipped | Cancelled | Exit code |
|---|---|---|---|---|---|
| ${summary.tests} | ${summary.pass} | ${summary.fail} | ${summary.skipped} | ${summary.cancelled} | ${t.status} |

Full output: [test-run.txt](test-run.txt). Machine-readable: [test-summary.json](test-summary.json).

Skipped tests are POSIX-only symlink checks that cannot run on Windows. Linux and macOS results come from the public GitHub Actions runs, not from this file.

## Sample runs: exit codes behave as documented

| Command | Exit code | Documented | Matches |
|---|---|---|---|
${exitTable}

## Sample artifacts

- Good evidence: [report.json](samples/good/report.json), [report.md](samples/good/report.md), [report.html](samples/good/report.html), [junit.xml](samples/good/junit.xml)
- Bad evidence (forbidden tool + canary leak, missing latency): [report.json](samples/bad/report.json), [report.md](samples/bad/report.md), [report.html](samples/bad/report.html), [junit.xml](samples/bad/junit.xml)
- Regression comparison: [compare-good-vs-bad.json](samples/compare-good-vs-bad.json)
- Release gate on the bad run: [gate-bad-run.json](samples/gate-bad-run.json)
- Trace analysis: [trace-analysis.json](samples/trace-analysis.json)
- Self-audit: [audit-report.md](samples/audit/audit-report.md), [audit-report.html](samples/audit/audit-report.html), [audit-report.json](samples/audit/audit-report.json)

## Honest limits

- Observations are **synthetic fixtures**. They show the evaluator behaves correctly; they say nothing about any real agent.
- The self-audit runs in the same process as the code it checks. It is an integrity check, not a third-party attestation.
- No live IDE, model or cloud service was used to produce any file here.
`;
writeFileSync(join(EV, 'README.md'), readme);
const bad_ = [r1.status !== 0, r2.status !== 2, cmp.status !== 2, gate.status !== 2, trace.status !== 2, audit.status !== 0, t.status !== 0].some(Boolean);
console.log(`evidence: tests=${summary.tests} pass=${summary.pass} fail=${summary.fail} skipped=${summary.skipped}${bad_ ? ' PROBLEM' : ' ok'}`);
process.exit(bad_ ? 1 : 0);
